import re
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, status
from pydantic import BaseModel
from sqlalchemy.orm import Session

from app.database.connection import SessionLocal
from app.models.interview_question import InterviewQuestion
from app.services.question_generator import generate_questions


router = APIRouter(
    prefix="/ai",
    tags=["AI Interview"]
)


class QuestionRequest(BaseModel):
    session_id: Optional[int] = 0
    job_role: str
    difficulty: str = "Medium"
    count: int = 5
    avoid_questions: Optional[List[str]] = None


def get_db():
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()


@router.post("/generate-questions", status_code=status.HTTP_201_CREATED)
def generate_interview_questions(
    request: QuestionRequest,
    db: Session = Depends(get_db)
):
    past_questions = []

    # Fetch previous questions for the current session if provided
    if request.session_id and request.session_id > 0:
        try:
            existing_db_questions = db.query(InterviewQuestion.question).filter(
                InterviewQuestion.session_id == request.session_id
            ).all()
            past_questions = [q[0] for q in existing_db_questions if q[0]]
        except Exception:
            pass

    # Include any questions the client asked to avoid (from past interview history)
    if request.avoid_questions:
        for aq in request.avoid_questions:
            if aq and aq not in past_questions:
                past_questions.append(aq)

    # Also fetch recent questions across other recent sessions from the database
    # to guarantee questions are never repeated across different interview attempts
    try:
        recent_db_questions = (
            db.query(InterviewQuestion.question)
            .order_by(InterviewQuestion.id.desc())
            .limit(30)
            .all()
        )
        for rq in recent_db_questions:
            if rq[0] and rq[0] not in past_questions:
                past_questions.append(rq[0])
    except Exception:
        pass

    # Generate questions using Groq LLM
    try:
        questions_text = generate_questions(
            job_role=request.job_role,
            difficulty=request.difficulty,
            count=request.count,
            avoid_questions=past_questions
        )
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to generate questions: {str(e)}"
        )

    # Split numbered AI response into individual questions cleanly
    raw_blocks = re.split(r'(?:^|\n)\s*\d+[\.\)]\s*', questions_text)
    questions = []
    for b in raw_blocks:
        b_clean = b.strip()
        if not b_clean:
            continue
        # Remove markdown bold headers like **Question 1:**
        b_clean = re.sub(r'^\*\*Question\s*\d*:?\*\*\s*', '', b_clean, flags=re.IGNORECASE).strip()
        if b_clean.lower().startswith("here are") or b_clean.lower().startswith("sure"):
            continue
        if len(b_clean) > 8:
            questions.append(b_clean)

    # Fallback to line splitting if re.split did not catch them
    if not questions:
        for line in questions_text.splitlines():
            line = line.strip()
            if line:
                cleaned = line.lstrip("0123456789").lstrip(".-*) ").strip()
                if cleaned and len(cleaned) > 10 and not cleaned.lower().startswith("here"):
                    questions.append(cleaned)

    if not questions:
        raise HTTPException(
            status_code=500,
            detail="No questions were generated by AI."
        )

    questions = questions[:request.count]

    # Save questions into database if session_id is provided
    saved_items = []
    if request.session_id and request.session_id > 0:
        try:
            for question in questions:
                new_question = InterviewQuestion(
                    session_id=request.session_id,
                    question=question,
                    question_type="AI Generated",
                    difficulty=request.difficulty
                )
                db.add(new_question)
                saved_items.append(new_question)
            db.commit()
            for q in saved_items:
                db.refresh(q)
        except Exception as e:
            print(f"Notice: Could not persist questions to DB ({e}), returning directly to client.")

    return {
        "message": "Questions generated successfully",
        "session_id": request.session_id,
        "job_role": request.job_role,
        "difficulty": request.difficulty,
        "questions": [
            {
                "id": saved_items[i].id if i < len(saved_items) else i + 1,
                "question": q,
                "question_type": "AI Generated",
                "difficulty": request.difficulty
            }
            for i, q in enumerate(questions)
        ]
    }
